static void fill_background(uint8_t* dst, uint32_t stride, uint32_t frame)
{
	for (int y = 0; y < VIDEO_HEIGHT; ++y)
	{
		uint8_t* row = dst + (uint32_t)y * stride;
		for (int x = 0; x < VIDEO_WIDTH; ++x)
		{
			uint8_t v = (uint8_t)(16 + (((x + (int)(frame >> 1)) >> 4) & 7));
			row[x] = v;
		}
	}
}

static void masked_blit_8(
	uint8_t* dst,
	uint32_t dst_stride,
	int dst_w,
	int dst_h,
	const uint8_t* src,
	int src_w,
	int src_h,
	int dst_x,
	int dst_y,
	uint8_t key)
{
	int src_x = 0;
	int src_y = 0;
	int w = src_w;
	int h = src_h;

	// Clip the source and destination rectangles to ensure we don't read/write out of screen bounds
	if (dst_x < 0)
	{
		src_x = -dst_x;
		dst_x = 0;
		w -= src_x;
	}
	if (dst_y < 0)
	{
		src_y = -dst_y;
		dst_y = 0;
		h -= src_y;
	}
	if (dst_x + w > dst_w)
		w = dst_w - dst_x;
	if (dst_y + h > dst_h)
		h = dst_h - dst_y;
	if (w <= 0 || h <= 0)
		return;

#if defined(__ARM_NEON) || defined(__ARM_NEON__)
	uint8x16_t keyv = vdupq_n_u8(key);				// Broadcast the key to 16 bytes
#endif

for (int y = 0; y < h; ++y)
	{
		uint8_t* d = dst + (uint32_t)(dst_y + y) * dst_stride + dst_x;
		const uint8_t* s = src + (src_y + y) * src_w + src_x;
		int x = 0;

		// If NEON is available, we can process 16 pixels at a time.
		// The key is compared against the source pixels, and if it matches,
		// the destination pixel is kept; otherwise, the source pixel is copied to the destination.
#if defined(__ARM_NEON) || defined(__ARM_NEON__)
		for (; x + 15 < w; x += 16)
		{
			uint8x16_t sv = vld1q_u8(s + x);			// Load source pixels
			uint8x16_t dv = vld1q_u8(d + x);			// Load destination pixels
			uint8x16_t mask = vceqq_u8(sv, keyv);		// Compare source pixels with key, result is 0xFF where equal, 0x00 where not
			uint8x16_t out = vbslq_u8(mask, dv, sv);	// If mask bit is 1, select from dv (keep dest), else select from sv (copy src)
			vst1q_u8(d + x, out);						// Store result back to destination
		}
#endif
		// Process any remaining pixels that don't fit into a 16-byte block
		for (; x < w; ++x)
		{
			uint8_t px = s[x];
			if (px != key)
				d[x] = px;
		}
	}
}

int main(int argc, char** argv)
{
	(void)argc; (void)argv;

	s_platform = SPInitPlatform();
	if (!s_platform)
	{
		fprintf(stderr, "Failed to init platform\n");
		return -1;
	}

	uint32_t stride = VPUGetStride(VIDEO_MODE, VIDEO_COLOR);
	frameBufferA.size = frameBufferB.size = stride * VIDEO_HEIGHT;
	SPAllocateBuffer(s_platform, &frameBufferA);
	SPAllocateBuffer(s_platform, &frameBufferB);

	VPUSetVideoMode(s_platform->vx, VIDEO_MODE, VIDEO_COLOR, EVS_Enable);
	init_palette(s_platform->vx);

	s_platform->sc->cycle = 0;
	s_platform->sc->framebufferA = &frameBufferA;
	s_platform->sc->framebufferB = &frameBufferB;

	VPUSetScanoutAddress(s_platform->vx, (uint32_t)frameBufferA.dmaAddress);
	VPUSetScanoutAddress2(s_platform->vx, (uint32_t)frameBufferB.dmaAddress);

	VPUSwapPages(s_platform->vx, s_platform->sc);
	VPUClear(s_platform->vx, 0x00000000);
	VPUSwapPages(s_platform->vx, s_platform->sc);
	VPUClear(s_platform->vx, 0x00000000);

	struct Sprite sprites[SPRITE_COUNT] = {
		{ 20, 30, 2, 1 },
		{ 140, 50, -2, 2 },
		{ 80, 160, 1, -2 },
		{ 200, 120, -1, -1 },
	};
	
	const uint8_t* sprite_data[SPRITE_COUNT] = {
		sprite_duck,
		sprite_cow,
		sprite_fox,
		sprite_rabbit,
	};

	uint32_t frame = 0;
	while (1)
	{
		while (VPUGetFIFONotEmpty(s_platform->vx)) { }
		VPUSwapPages(s_platform->vx, s_platform->sc);

		uint8_t* dst = (uint8_t*)s_platform->sc->writepage;
		fill_background(dst, stride, frame);

		for (int i = 0; i < SPRITE_COUNT; ++i)
		{
			struct Sprite* sp = &sprites[i];
			sp->x += sp->vx;
			sp->y += sp->vy;
			if (sp->x < 0) { sp->x = 0; sp->vx = -sp->vx; }
			if (sp->y < 0) { sp->y = 0; sp->vy = -sp->vy; }
			if (sp->x > (VIDEO_WIDTH - SPRITE_W)) { sp->x = VIDEO_WIDTH - SPRITE_W; sp->vx = -sp->vx; }
			if (sp->y > (VIDEO_HEIGHT - SPRITE_H)) { sp->y = VIDEO_HEIGHT - SPRITE_H; sp->vy = -sp->vy; }

			masked_blit_8(dst, stride, VIDEO_WIDTH, VIDEO_HEIGHT, sprite_data[i], SPRITE_W, SPRITE_H, sp->x, sp->y, TRANSPARENT_KEY);
		}

		const char* label = "NEON sprite blit demo";
		VPUPrintString(s_platform->vx, 15, 0, 4, 4, label, (int)strlen(label));

		VPUSyncSwap(s_platform->vx, 0);
		VPUNoop(s_platform->vx);
		++frame;
	}

	return 0;
}
